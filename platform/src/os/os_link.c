/*
 * os_link.c - REL modules.
 *
 * On the GameCube the game loads a module's .rel file from the disc and
 * OSLink relocates it in place; the game then calls the header's prolog.
 * In the port every module the decomp has is compiled and linked into the
 * image, with its _prolog/_epilog/_unresolved renamed to
 * <module>__prolog and so on (tools/unify_prototypes.py). OSLink finds the
 * module by the ID in the loaded header (tools/link_be.py generates the
 * table from the original .rel files) and points the header's prolog,
 * epilog and unresolved fields at those functions. The loaded image itself
 * is not used: code and data are already in place.
 *
 * Modules the decomp does not have yet cannot be linked; that stops with
 * the module's ID and name.
 */
#include <stdio.h>
#include <string.h>

#include "port/types.h"

extern void __port_fatal(const char* what);
extern void __port_log(const char* fmt, ...);

/* The REL header, as the SDK defines it (big-endian, as loaded). */
typedef struct OSModuleInfo {
    u32 id;
    struct OSModuleInfo* next;
    struct OSModuleInfo* prev;
    u32 numSections;
    u32 sectionInfoOffset;
    u32 nameOffset;
    u32 nameSize;
    u32 version;
} OSModuleInfo;

typedef struct OSModuleHeader {
    OSModuleInfo info;
    u32 bssSize;
    u32 relOffset;
    u32 impOffset;
    u32 impSize;
    u8 prologSection, epilogSection, unresolvedSection, bssSection;
    u32 prolog;
    u32 epilog;
    u32 unresolved;
} OSModuleHeader;

/* Generated by tools/link_be.py (build/port/modules.c). */
typedef struct {
    u32 id;
    const char* name;
    void (*prolog)(void);
    void (*epilog)(void);
    void (*unresolved)(void);
} PortModule;
extern const PortModule __port_modules[];
extern const u32 __port_module_count;

static OSModuleInfo* linked_head;

static const PortModule* find(u32 id)
{
    for (u32 i = 0; i < __port_module_count; i++)
        if (__port_modules[i].id == id)
            return &__port_modules[i];
    return 0;
}

int OSLink(OSModuleInfo* module, void* bss)
{
    OSModuleHeader* h = (OSModuleHeader*)module;
    const PortModule* m = find(module->id);
    if (!m) {
        char what[96];
        snprintf(what, sizeof(what), "OSLink: module %lu is not in the decomp", (unsigned long)module->id);
        __port_fatal(what);
    }
    /* The module's .bss is the game's allocation after the image; the
     * port's module data lives in the image, so it is not used. */
    (void)bss;
    h->prolog = (u32)m->prolog;
    h->epilog = (u32)m->epilog;
    h->unresolved = (u32)m->unresolved;
    module->prev = 0;
    module->next = linked_head;
    if (linked_head)
        linked_head->prev = module;
    linked_head = module;
    __port_log("OSLink: module %lu (%s)", (unsigned long)module->id, m->name);
    return 1;
}

/* OSUnlink in the SDK version the game uses (one argument). */
int fn_8009EFE4(OSModuleInfo* module)
{
    OSModuleHeader* h = (OSModuleHeader*)module;
    if (module->prev)
        module->prev->next = module->next;
    else if (linked_head == module)
        linked_head = module->next;
    if (module->next)
        module->next->prev = module->prev;
    module->next = module->prev = 0;
    h->prolog = h->epilog = h->unresolved = 0;
    return 1;
}
