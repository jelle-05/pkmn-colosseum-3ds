#!/usr/bin/env python3
"""Link the port: a big-endian image inside a little-endian 3dsx.

The game and the platform layer (platform/src) are compiled big-endian and
linked as a BE8 image: instructions little-endian, data big-endian, run
with the ARM11's data endianness set to big (SETEND BE). The host
(platform/host) is an ordinary little-endian libctru program that carries
the image and calls into it. See docs/BIG_ENDIAN.md.

Where things go:

    3dsx code segment   crt0, then the image's code and read-only data at
                        TEXT_BASE (fixed), then the host's code
    3dsx data segment   the image's initialised data first, then the host's
    3dsx bss            the image's zero-initialised data first, then the
                        host's

The image's data addresses depend on the size of the host's code, so the
link runs in passes: the image once to learn its sizes, the host with
placeholders of those sizes to learn the addresses, the image again at
those addresses, and the host with the real contents (same sizes, same
addresses; checked).

Missing symbols get stubs as in tools/link_probe.py (generated stubs.c,
compiled big-endian), and data is laid out at its GameCube offsets
(tools/gen_layout.py).

Usage:
    python tools/link_check.py
    python tools/link_be.py
"""

import json
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import compile_check  # noqa: E402
import gen_layout  # noqa: E402
from link_probe import read_symbols, c_name  # noqa: E402
from access_widths import symbol_addresses  # noqa: E402

BIN = compile_check.DEVKITARM / "bin"
DEVKITPRO = compile_check.DEVKITARM.parent
GCC = BIN / "arm-none-eabi-gcc.exe"
NM = BIN / "arm-none-eabi-nm.exe"
OBJCOPY = BIN / "arm-none-eabi-objcopy.exe"
READELF = BIN / "arm-none-eabi-readelf.exe"
BE_LIBGCC = compile_check.DEVKITARM / "lib" / "gcc" / "arm-none-eabi" / "16.1.0" / "be"
BE_LIBC = compile_check.DEVKITARM / "arm-none-eabi" / "lib" / "be"
OUT = ROOT / "build" / "port"

TEXT_BASE = 0x00101000          # after crt0 in the 3dsx code segment
CRT0_GAP = TEXT_BASE - 0x00100000


def run(cmd, what):
    p = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if p.returncode:
        sys.exit(f"{what} failed:\n{(p.stdout + p.stderr)[-4000:]}")
    return p.stdout


def compile_all(sources, out_dir, base, flags):
    objs = []

    def one(src):
        obj = out_dir / src.relative_to(base).with_suffix(".o")
        obj.parent.mkdir(parents=True, exist_ok=True)
        run([GCC, *flags, "-c", src, "-o", obj], f"compiling {src.name}")
        return obj
    with ThreadPoolExecutor() as pool:
        objs = list(pool.map(one, sources))
    return objs


def defined(obj, kinds="TDBRSW"):
    out = subprocess.run([str(NM), "--defined-only", str(obj)], capture_output=True, text=True).stdout
    return {l.split()[-1] for l in out.splitlines() if len(l.split()) == 3 and l.split()[1] in kinds}


def undefined_syms(obj):
    out = subprocess.run([str(NM), "-u", str(obj)], capture_output=True, text=True).stdout
    return {l.split()[-1] for l in out.splitlines() if l.strip()}


def symbols(elf):
    out = run([NM, elf], "nm")
    return {p[2]: int(p[0], 16) for p in (l.split() for l in out.splitlines()) if len(p) == 3}


def sections(elf):
    out = run([READELF, "-SW", elf], "readelf")
    res = {}
    for line in out.splitlines():
        m = re.match(r"^\s*\[\s*\d+\]\s+(\S+)\s+(\S+)\s+([0-9a-f]+)\s+[0-9a-f]+\s+([0-9a-f]+)\s+\S+\s+(\S*)", line)
        if m and m.group(1) != "NULL":
            res[m.group(1)] = (m.group(2), int(m.group(3), 16), int(m.group(4), 16), m.group(5))
    return res


# ---- the big-endian image ---------------------------------------------------------

BE_SCRIPT = """\
/* Generated by tools/link_be.py. The big-endian image. */
ENTRY(__be_start)
SECTIONS
{{
    . = {text:#x};
    .text : {{
        *(.text .text.* .gnu.linkonce.t.*)
        *(.glue_7 .glue_7t .vfp11_veneer .v4_bx)
    }}
    .rodata : ALIGN(8) {{
        *(.rodata .rodata.* .gnu.linkonce.r.*)
    }}
    .init_array : ALIGN(4) {{
        __be_init_array_start = .;
        KEEP(*(SORT_BY_INIT_PRIORITY(.init_array.*)))
        KEEP(*(.init_array .ctors))
        __be_init_array_end = .;
    }}
    .ARM.extab : {{ *(.ARM.extab* .gnu.linkonce.armextab.*) }}
    .ARM.exidx : {{ __exidx_start = .; *(.ARM.exidx* .gnu.linkonce.armexidx.*) __exidx_end = .; }}
    __be_text_end = .;

    . = {data:#x};
{data_blocks}
    .data : ALIGN(8) {{
        *(.data .data.* .gnu.linkonce.d.*)
        *(.sdata .sdata.*)
    }}
    __be_data_end = .;

    . = {bss:#x};
{bss_blocks}
    .bss (NOLOAD) : ALIGN(8) {{
        *(.bss .bss.* .gnu.linkonce.b.* COMMON)
        *(.sbss .sbss.*)
    }}
    __be_bss_end = .;

    /DISCARD/ : {{ *(.fini_array*) *(.dtors*) *(.comment) *(.note*) }}
}}
{aliases}
"""


# Soft-float library functions that pass a float or double in core
# registers, where hard-float callers use VFP registers. None may be
# linked from the big-endian newlib or libgcc; the image provides its own
# (rt/hf_conv.c) or must not use them. Variadic functions (sprintf) are
# fine: variadic arguments travel in core registers in both ABIs.
SOFT_FLOAT_ONLY = re.compile(
    r"^(?:__aeabi_(?:[fd](?:add|sub|rsub|mul|div|cmp\w*|2\w+)|[ui]?l?2[fd]|[ui]2[fd])|"
    r"strto(?:d|f|ld)|atof|[fl]?d?exp\w*|frexp\w*|ldexp\w*|modf\w*|fmod\w*|sqrt\w*|pow\w*|"
    r"sin\w*|cos\w*|tan\w*|a(?:sin|cos|tan)\w*|floor\w*|ceil\w*|fabs\w*|log\w*|round\w*|trunc\w*)$")


def check_soft_float(map_path, objs):
    """Refuse soft-float functions from the libraries that our objects call.
    (The libraries calling each other is fine: they agree on the ABI.) The
    map only names the first reference, so the objects' own undefined
    symbols are checked as well."""
    text = map_path.read_text(encoding="utf-8", errors="replace")
    pulled = re.findall(r"^\S*[\\/](?:be)[\\/](lib\w+\.a)\((\S+?\.o)\)\s*\n?\s*(\S+?\.o|\S+)\s+\((\S+)\)",
                        text, re.M)
    from_lib = {sym: (lib, member) for lib, member, by, sym in pulled}
    with ThreadPoolExecutor() as pool:
        wanted = set().union(*pool.map(undefined_syms, objs))
    ours = {o.resolve().as_posix() for o in objs}
    provided_by_us = set()
    with ThreadPoolExecutor() as pool:
        for d in pool.map(defined, objs):
            provided_by_us |= d
    bad = sorted({(from_lib.get(s, ("?", "?"))[0], from_lib.get(s, ("?", "?"))[1], s)
                  for s in wanted if SOFT_FLOAT_ONLY.match(s) and s not in provided_by_us})
    del ours
    if bad:
        sys.exit("soft-float library functions linked into the image:\n" +
                 "\n".join(f"  {sym} from {lib}({member})" for lib, member, sym in bad))


def link_image(objs, addrs, blocks, aliases, tag):
    data_blocks, bss_blocks = blocks
    script = OUT / f"image_{tag}.ld"
    script.write_text(BE_SCRIPT.format(
        text=TEXT_BASE, data=addrs[0], bss=addrs[1],
        data_blocks="\n".join(data_blocks), bss_blocks="\n".join(b.replace(" ALIGN(0x20) :", " ALIGN(0x20) (NOLOAD) :")
                                                                   for b in bss_blocks),
        aliases="".join(f"{n} = {p} + {d};\n" for n, (p, d) in sorted(aliases.items()))), encoding="utf-8")
    rsp = OUT / f"image_{tag}.rsp"
    rsp.write_text("\n".join(o.as_posix() for o in objs) + "\n", encoding="utf-8")
    elf = OUT / f"image_{tag}.elf"
    run([GCC, *compile_check.ARCH, "-mbe8", "-nostdlib", "-nostartfiles", "-T", script,
         f"@{rsp.as_posix()}", "-Wl,--start-group",
         BE_LIBC / "libc.a", BE_LIBGCC / "libgcc.a", "-Wl,--end-group",
         "-Wl,--gc-sections", "-Wl,--allow-multiple-definition",
         # The big-endian newlib and libgcc are soft-float builds. Their ABI
         # tag differs; what is linked from them is checked below instead.
         "-Wl,--no-warn-mismatch",
         f"-Wl,-Map,{(OUT / f'image_{tag}.map').as_posix()}", "-o", elf], f"linking the image ({tag})")
    check_soft_float(OUT / f"image_{tag}.map", objs)
    sym = symbols(elf)
    sizes = (sym["__be_text_end"] - TEXT_BASE, sym["__be_data_end"] - addrs[0], sym["__be_bss_end"] - addrs[1])
    # Nothing writable may land in the code region, nothing else in the gaps.
    for name, (kind, addr, size, flags) in sections(elf).items():
        if not addr or not size:
            continue
        # .init_array is only read (by __be_start), though marked writable.
        if TEXT_BASE <= addr < TEXT_BASE + sizes[0] and "W" in flags and name != ".init_array":
            sys.exit(f"writable section {name} in the image's code region")
    return elf, sym, sizes


# ---- the host ---------------------------------------------------------------------

HOST_IMAGE = """\
@ Generated by tools/link_be.py: the big-endian image, as the host carries it.
    .section .be_text, "ax"
    .global __be_text_at
__be_text_at:
{text}
    .section .be_data, "aw"
    .balign 32
    .global __be_data_at
__be_data_at:
{data}
    .section .be_bss, "aw", %nobits
    .balign 32
    .global __be_bss_at
__be_bss_at:
    .space {bss}
"""


def host_script():
    base = gen_layout.BASE_LD.read_text(encoding="utf-8")
    k = base.index("KEEP( *(.crt0) )")
    e = base.index("\n", k)
    base = base[:e] + f"\n\t\t. = {CRT0_GAP:#x};\n\t\tKEEP( *(.be_text) )\n" + base[e:]
    k = base.index("=========== DATA section")
    k = base.index(".data :", k)
    e = base.index("{", k) + 1
    base = base[:e] + "\n\t\tKEEP( *(.be_data) )\n" + base[e:]
    k = base.index(".bss ALIGN(4) :")
    e = base.index("{", k) + 1
    base = base[:e] + "\n\t\tKEEP( *(.be_bss) )\n" + base[e:]
    script = OUT / "host.ld"
    script.write_text(base, encoding="utf-8")
    specs = OUT / "host.specs"
    specs.write_text("%include <sync-dmb.specs>\n\n*link:\n"
                     f"+ -T {script.as_posix()} -d --emit-relocs --use-blx --gc-sections\n\n"
                     "*startfile:\n3dsx_crt0%O%s crti%O%s crtbegin%O%s\n", encoding="utf-8")
    return specs


def link_host(host_objs, specs, image_sym, sizes, text_bin, data_bin, tag):
    src = OUT / f"host_image_{tag}.S"
    if text_bin:
        text = f'    .incbin "{text_bin.as_posix()}"'
        data = f'    .incbin "{data_bin.as_posix()}"'
    else:
        text = f"    .space {sizes[0]}"
        data = f"    .space {sizes[1]}"
    src.write_text(HOST_IMAGE.format(text=text, data=data, bss=sizes[2]), encoding="utf-8")
    obj = OUT / f"host_image_{tag}.o"
    run([GCC, *compile_check.ARCH_LE, "-c", src, "-o", obj], "assembling the host image")
    elf = OUT / f"colosseum_{tag}.elf"
    run([GCC, f"-specs={specs.as_posix()}", *compile_check.ARCH_LE, *host_objs, obj,
         f"-Wl,--defsym,__host_table={image_sym['__host_table']:#x}",
         f"-Wl,--defsym,__be_start={image_sym['__be_start']:#x}",
         "-L", DEVKITPRO / "libctru" / "lib", "-lcitro3d", "-lctru", "-lm",
         f"-Wl,-Map,{(OUT / f'colosseum_{tag}.map').as_posix()}", "-o", elf], f"linking the host ({tag})")
    sym = symbols(elf)
    return elf, (sym["__be_text_at"], sym["__be_data_at"], sym["__be_bss_at"])


# ---- stubs --------------------------------------------------------------------------

def make_stubs(report, syms, provided, game_objs, decomp):
    """stubs.c for what is still missing; data labels inside a larger game
    object become aliases (see link_probe.py)."""
    import bisect

    def data_sizes(obj):
        out = subprocess.run([str(NM), "-S", "--defined-only", str(obj)], capture_output=True, text=True).stdout
        return {p[3]: int(p[1], 16) for p in (l.split() for l in out.splitlines())
                if len(p) == 4 and p[2] in "DdBbRr"}
    with ThreadPoolExecutor() as pool:
        game_data = {}
        for d in pool.map(data_sizes, game_objs):
            game_data.update(d)
    retail = symbol_addresses(decomp)
    spaces = {}
    for name, size in game_data.items():
        if name in retail:
            space, addr, _ = retail[name]
            spaces.setdefault(space, []).append((addr, size, name))
    for v in spaces.values():
        v.sort()
    starts = {k: [a for a, _, _ in v] for k, v in spaces.items()}

    def container(name):
        if name not in retail:
            return None
        space, addr, _ = retail[name]
        k = bisect.bisect_right(starts.get(space, []), addr) - 1
        if k < 0:
            return None
        paddr, psize, parent = spaces[space][k]
        if parent != name and paddr < addr < paddr + psize:
            return parent, addr - paddr
        return None

    aliases, counts = {}, {}
    lines = ["/* Generated by tools/link_be.py. Do not edit. */",
             "extern void __port_stub(const char* name);", ""]
    i = 0
    for group, names in sorted(report["left_by_category"].items()):
        lines.append(f"/* ---- {group}: {len(names)} */")
        for name in sorted(names):
            if name in provided:
                continue
            kind, size, align = syms.get(name, ("function", 0, 8))
            i += 1
            label = name.replace("\\", "\\\\").replace('"', '\\"')
            if kind == "function" or (kind not in ("object",) and size == 0):
                lines.append(f'void {c_name(name, i)}(void) __asm__("{label}");')
                lines.append(f'void {c_name(name, i)}(void) {{ __port_stub("{label}"); }}')
            elif container(name):
                aliases[name] = container(name)
                lines.append(f"/* {name} = {aliases[name][0]} + {aliases[name][1]:#x} (linker script) */")
            else:
                lines.append(f'unsigned char {c_name(name, i)}[{max(size, 1)}] '
                             f'__asm__("{label}") __attribute__((aligned({align})));')
            counts[group] = counts.get(group, 0) + 1
        lines.append("")
    stubs = OUT / "stubs.c"
    stubs.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return stubs, aliases, counts, i


def build_shaders(hsrc, le_flags):
    """Every platform/host/NAME.v.pica, assembled with picasso and embedded
    as NAME_shbin / NAME_shbin_size."""
    picasso = DEVKITPRO / "tools" / "bin" / "picasso.exe"
    objs = []
    for src in sorted(hsrc.glob("*.v.pica")):
        name = src.name.split(".")[0]
        shbin = OUT / "host" / f"{name}.shbin"
        shbin.parent.mkdir(parents=True, exist_ok=True)
        run([picasso, "-o", shbin, src], f"assembling {src.name}")
        asm = OUT / "host" / f"{name}_shbin.S"
        asm.write_text(
            "    .section .rodata\n    .balign 4\n"
            f"    .global {name}_shbin, {name}_shbin_size\n"
            f"{name}_shbin:\n    .incbin \"{shbin.as_posix()}\"\n{name}_shbin_end:\n    .balign 4\n"
            f"{name}_shbin_size:\n    .word {name}_shbin_end - {name}_shbin\n", encoding="utf-8")
        obj = asm.with_suffix(".o")
        run([GCC, *compile_check.ARCH_LE, "-c", asm, "-o", obj], f"embedding {name}.shbin")
        objs.append(obj)
    return objs


def localize_private_inlines(objs):
    """Inline functions become weak definitions (unify_prototypes.py), so
    the linker keeps one copy for units that call them from outside. But
    some names are unit-private helpers with different bodies in different
    units (the decomp has several `inline_fn`): there one copy for all is
    wrong. A weak function defined with different sizes in several objects
    is made local in each of them, so every unit calls its own."""
    from collections import defaultdict

    def weak_defs(obj):
        out = subprocess.run([str(NM), "-S", "--defined-only", str(obj)], capture_output=True, text=True).stdout
        return obj, [(p[3], int(p[1], 16)) for p in (l.split() for l in out.splitlines())
                     if len(p) == 4 and p[2] == "W"]
    defs = defaultdict(list)
    with ThreadPoolExecutor() as pool:
        for obj, ws in pool.map(weak_defs, objs):
            for name, size in ws:
                defs[name].append((obj, size))
    private = {n: d for n, d in defs.items() if len(d) > 1 and len({s for _, s in d}) > 1}
    if not private:
        return
    with ThreadPoolExecutor() as pool:
        users = set().union(*pool.map(undefined_syms, objs))
    per_obj = defaultdict(list)
    for name, d in private.items():
        for obj, _ in d:
            per_obj[obj].append(name)
    for obj, names in per_obj.items():
        run([OBJCOPY, *(f"--localize-symbol={n}" for n in names), obj], f"localizing in {obj.name}")
    shared = sorted(n for n in private if n in users)
    print(f"unit-private inline functions made local: {', '.join(sorted(private))}"
          + (f" (also called from other units, now unresolved there: {', '.join(shared)})" if shared else ""))


def make_modules(decomp, manifest, game_defined):
    """modules.c: the REL modules compiled into the image, by the module ID
    in their original .rel header, for OSLink (platform/src/os/os_link.c)."""
    import struct
    names = sorted({u["module"] for u in manifest["units"] if u["module"] != "main"})
    lines = ["/* Generated by tools/link_be.py. Do not edit. */",
             "typedef struct { unsigned id; const char* name; void (*prolog)(void);",
             "                 void (*epilog)(void); void (*unresolved)(void); } PortModule;", ""]
    rows = []
    for name in names:
        rel = decomp / "orig" / "GC6E01" / "files" / f"{name}.rel"
        if not rel.exists():
            print(f"  module {name}: no original .rel, left out")
            continue
        mid = struct.unpack(">I", rel.read_bytes()[:4])[0]
        fns = []
        for part in ("prolog", "epilog", "unresolved"):
            sym = f"{name}__{part}"
            if sym in game_defined:
                lines.append(f"extern void {sym}(void);")
                fns.append(sym)
            else:
                fns.append("0")
        rows.append(f'    {{ {mid}u, "{name}", {", ".join(fns)} }},')
    lines += ["", "const PortModule __port_modules[] = {", *rows, "};",
              f"const unsigned __port_module_count = {len(rows)};", ""]
    out = OUT / "modules.c"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    report = json.loads((ROOT / "build" / "link_check" / "report.json").read_text(encoding="utf-8"))
    manifest = json.loads((ROOT / "build" / "objects.json").read_text(encoding="utf-8"))
    decomp = Path(manifest["decomp"])
    syms = read_symbols(decomp)
    # What the big-endian newlib provides is not stubbed (sprintf, strcpy, ...).
    # Nor what libgcc provides (__aeabi_idiv ...); the math library comes
    # from the host (HOST_LIBM in port/host.h, stubs in the platform).
    libc_defs = set()
    for lib in (BE_LIBC / "libc.a", BE_LIBGCC / "libgcc.a"):
        libc_defs |= {p[2] for p in (l.split() for l in run([NM, "--defined-only", lib], "nm")
                                     .splitlines()) if len(p) == 3 and p[1] in "TW"}

    be_flags = [*compile_check.ARCH, "-O1", "-std=gnu99", "-fno-common", "-fdata-sections",
                "-ffunction-sections", "-fno-math-errno", "-D__3DS__", "-DPORT_BIG_ENDIAN=1",
                "-I", ROOT / "platform" / "include"]
    le_flags = [*compile_check.ARCH_LE, "-O2", "-std=gnu99", "-D__3DS__",
                "-I", DEVKITPRO / "libctru" / "include", "-I", ROOT / "platform" / "include"]

    psrc = ROOT / "platform" / "src"
    platform_objs = compile_all(sorted(psrc.rglob("*.c")) + sorted(psrc.rglob("*.S")),
                                OUT / "platform", psrc, be_flags)
    hsrc = ROOT / "platform" / "host"
    host_objs = compile_all(sorted(hsrc.rglob("*.c")) + sorted(hsrc.rglob("*.S")),
                            OUT / "host", hsrc, le_flags)
    host_objs += build_shaders(hsrc, le_flags)

    results = json.loads((ROOT / "build" / "unified" / "compile.json").read_text(encoding="utf-8"))
    game_objs = [ROOT / "build" / "unified" / "obj" / (r["name"] + ".o") for r in results if r["ok"]]

    localize_private_inlines(game_objs)

    with ThreadPoolExecutor() as pool:
        provided = set().union(*pool.map(defined, platform_objs))
        game_defined = set().union(*pool.map(lambda o: defined(o, "TDBRS"), game_objs))
    strong_platform = set().union(*(defined(o, "TDBRS") for o in platform_objs))
    clash = sorted(strong_platform & game_defined)
    if clash:
        sys.exit("platform/src defines symbols the game also defines: " + ", ".join(clash))

    stubs, aliases, counts, n_stubs = make_stubs(report, syms, provided | libc_defs, game_objs, decomp)
    modules = make_modules(decomp, manifest, game_defined)
    stubs_obj, modules_obj = compile_all([stubs, modules], OUT / "gen", OUT, be_flags)
    image_objs = game_objs + [stubs_obj, modules_obj] + platform_objs

    data_blocks, bss_blocks, placed, skipped, problems = gen_layout.blocks(image_objs, decomp)
    (OUT / "layout_problems.txt").write_text("\n".join(problems) + "\n", encoding="utf-8")
    blocks = (data_blocks, bss_blocks)
    print(f"layout: {placed} data symbols at their GameCube offsets, {skipped} not "
          f"(build/port/layout_problems.txt)")

    # Pass 1: sizes. Pass 2: addresses from the host. Pass 3: the image at
    # those addresses. Pass 4: the host with the real image.
    _, sym1, sizes = link_image(image_objs, (0x01000000, 0x02000000), blocks, aliases, "sizes")
    specs = host_script()
    _, at = link_host(host_objs, specs, sym1, sizes, None, None, "placeholder")
    if at[0] != TEXT_BASE:
        sys.exit(f"the image's code landed at {at[0]:#x}, not {TEXT_BASE:#x} (crt0 grew?)")
    image, sym, sizes2 = link_image(image_objs, (at[1], at[2]), blocks, aliases, "final")
    if sizes2 != sizes:
        sys.exit(f"image sizes changed between passes: {sizes} -> {sizes2}")
    text_bin, data_bin = OUT / "be_text.bin", OUT / "be_data.bin"
    run([OBJCOPY, "-O", "binary", "--only-section=.text", "--only-section=.rodata",
         "--only-section=.init_array", "--only-section=.ARM.extab", "--only-section=.ARM.exidx",
         image, text_bin], "extracting the image's code")
    data_sections = [s for s in sections(image) if s.startswith(".gc_") or s == ".data"]
    data_sections = [s for s in data_sections if sections(image)[s][0] != "NOBITS"]
    run([OBJCOPY, "-O", "binary", *(f"--only-section={s}" for s in data_sections), image, data_bin],
        "extracting the image's data")
    # objcopy pads between sections but not at the end: pad to the full size.
    for path, size in ((text_bin, sizes[0]), (data_bin, sizes[1])):
        b = path.read_bytes()
        if len(b) > size:
            sys.exit(f"{path.name} is {len(b)} bytes, larger than the region ({size})")
        path.write_bytes(b + bytes(size - len(b)))
    elf, at2 = link_host(host_objs, specs, sym, sizes, text_bin, data_bin, "final")
    if at2 != at:
        sys.exit(f"the host moved the image between passes: {at} -> {at2}")

    target = OUT / "colosseum.3dsx"
    final = OUT / "colosseum.elf"
    final.write_bytes(elf.read_bytes())
    run([DEVKITPRO / "tools" / "bin" / "3dsxtool.exe", final, target], "3dsxtool")
    print(f"image: code {sizes[0]:,} bytes at {TEXT_BASE:#x}, data {sizes[1]:,} at {at[1]:#x}, "
          f"bss {sizes[2]:,} at {at[2]:#x}")
    print(f"linked {len(game_objs)} game objects, {len(platform_objs)} platform and "
          f"{len(host_objs)} host objects, {n_stubs} stubs")
    for g, n in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f"  {n:5} stubs  {g}")
    print(f"-> {target} ({target.stat().st_size:,} bytes)")


