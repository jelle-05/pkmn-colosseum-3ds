#!/usr/bin/env python3
"""Turn the decomp's generated data units into big-endian ARM assembly.

43 of the decomp's units have no C source: their data is authored as .json
and a decomp tool builds the object (battle scripts, the message catalogue
and templates of common_rel, and the bytecode of common_rel's script
bank). The decomp builds them as PowerPC objects in
build/GC6E01/src/<unit>.o. Without them the port linked zeros in their
place: common_rel's script VM ran through 8 KB of zeros into the next
table and wrote 26,000 words over memory.

The data is already big-endian, as the port's image is, so the bytes are
copied as they are. The only relocations are R_PPC_ADDR32 (pointers),
which become `.4byte symbol+addend`. Each symbol goes in a section of its
own, aligned to 1, so that tools/gen_layout.py puts it at its retail
offset; bytes between two symbols belong to the first.

Used by tools/link_be.py:  sources(manifest, decomp, out_dir) -> [.S paths]
"""

import struct
import sys
from pathlib import Path

R_PPC_ADDR32 = 1
PREFIX = {".data": ".data", ".sdata": ".sdata", ".rodata": ".rodata", ".sdata2": ".rodata",
          ".bss": ".bss", ".sbss": ".sbss", ".sbss2": ".sbss"}


class Elf:
    def __init__(self, path):
        d = path.read_bytes()
        if d[:4] != b"\x7fELF" or d[4] != 1 or d[5] != 2:
            raise ValueError(f"{path}: not a 32-bit big-endian ELF")
        shoff, = struct.unpack_from(">I", d, 0x20)
        shentsize, shnum, shstrndx = struct.unpack_from(">HHH", d, 0x2E)
        self.sec = []
        for i in range(shnum):
            name, typ, flags, addr, off, size, link, info, align, entsize = \
                struct.unpack_from(">10I", d, shoff + i * shentsize)
            self.sec.append(dict(name=name, type=typ, flags=flags, off=off, size=size,
                                 link=link, info=info, align=align, entsize=entsize))
        strtab = self.sec[shstrndx]
        for s in self.sec:
            s["name"] = self._str(d, strtab["off"], s["name"])
        self.data = d
        self.syms = []
        for s in self.sec:
            if s["type"] == 2:                                   # SHT_SYMTAB
                st = self.sec[s["link"]]["off"]
                for j in range(s["size"] // 16):
                    name, value, size, info, other, shndx = struct.unpack_from(">IIIBBH", d, s["off"] + j * 16)
                    self.syms.append(dict(name=self._str(d, st, name), value=value, size=size,
                                          bind=info >> 4, type=info & 15, shndx=shndx))
        self.relocs = {}                                         # section index -> [(off, type, sym, addend)]
        for s in self.sec:
            if s["type"] == 4:                                   # SHT_RELA
                lst = self.relocs.setdefault(s["info"], [])
                for j in range(s["size"] // 12):
                    off, info, add = struct.unpack_from(">IIi", d, s["off"] + j * 12)
                    lst.append((off, info & 0xFF, info >> 8, add))

    @staticmethod
    def _str(d, base, off):
        end = d.index(b"\0", base + off)
        return d[base + off:end].decode("ascii")


def convert(obj, skip):
    """Assembly for one PowerPC object; `skip`: names the port already defines.
    -> (text, defined names, skipped names)"""
    e = Elf(obj)
    out = [f"@ Generated by tools/ppc_data.py from {obj.name}. Do not edit.", ""]
    defined, skipped = [], []
    for si, s in enumerate(e.sec):
        if s["name"] not in PREFIX or not s["size"]:
            continue
        nobits = s["type"] == 8
        syms = sorted((x for x in e.syms if x["shndx"] == si and x["type"] in (0, 1) and x["name"]
                       and x["bind"] in (0, 1) and not x["name"].startswith(".")), key=lambda x: x["value"])
        if not syms:
            if any(b for b in e.data[s["off"]:s["off"] + s["size"]]) and not nobits:
                raise ValueError(f"{obj}: {s['name']} has data but no symbols")
            continue
        relocs = {r[0]: r for r in e.relocs.get(si, [])}
        # Pointers whose target is a section symbol of this object resolve
        # to the symbol that contains the target.
        def target(r):
            t = e.syms[r[2]]
            if t["type"] == 3 or not t["name"]:                  # STT_SECTION
                off = r[3] + t["value"]
                inner = [x for x in syms if x["value"] <= off] if t["shndx"] == si else []
                if not inner:
                    raise ValueError(f"{obj}: pointer into section {t['shndx']} at {off:#x}")
                base = inner[-1]
                return f"{base['name']}+{off - base['value']}"
            return t["name"] + (f"+{r[3]}" if r[3] > 0 else f"{r[3]}" if r[3] < 0 else "")

        for k, x in enumerate(syms):
            start = x["value"]
            end = syms[k + 1]["value"] if k + 1 < len(syms) else s["size"]
            end = max(end, start + x["size"])
            if x["name"] in skip:
                skipped.append(x["name"])
                continue
            sec = f"{PREFIX[s['name']]}.{x['name']}"
            flags = '"a"' if PREFIX[s["name"]] == ".rodata" else '"aw"'
            out.append(f'\t.section {sec},{flags},%{"nobits" if nobits else "progbits"}')
            out.append("\t.balign 1")
            if x["bind"] == 1:
                out.append(f"\t.global {x['name']}")
            out.append(f"\t.type {x['name']}, %object")
            out.append(f"{x['name']}:")
            if nobits:
                out.append(f"\t.zero {end - start}")
            else:
                p = start
                run = []
                def flush():
                    for i in range(0, len(run), 16):
                        out.append("\t.byte " + ",".join(str(b) for b in run[i:i + 16]))
                    run.clear()
                while p < end:
                    r = relocs.get(p)
                    if r:
                        if r[1] != R_PPC_ADDR32:
                            raise ValueError(f"{obj}: relocation type {r[1]} at {p:#x}")
                        flush()
                        out.append(f"\t.4byte {target(r)}")
                        p += 4
                    else:
                        run.append(e.data[s["off"] + p])
                        p += 1
                flush()
            out.append(f"\t.size {x['name']}, {end - start}")
            out.append("")
            defined.append(x["name"])
    return "\n".join(out) + "\n", defined, skipped


def sources(manifest, decomp, out_dir, skip):
    """Write a .S for every generated unit; -> ([paths], report lines)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths, report = [], []
    for u in manifest["units"]:
        if u["group"] != "generated":
            continue
        rel = u["name"].split("/", 1)[1]
        obj = decomp / "build" / "GC6E01" / "src" / (rel + ".o")
        if not obj.is_file():
            sys.exit(f"{obj} not found: build the decomp (ninja) first")
        text, defined, skipped = convert(obj, skip)
        path = out_dir / (rel.replace("/", "__") + ".S")
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
        paths.append(path)
        report.append(f"{u['name']}: {len(defined)} symbols" + (f", {len(skipped)} already defined: "
                                                                  + " ".join(skipped) if skipped else ""))
    return paths, report


if __name__ == "__main__":
    import json
    root = Path(__file__).resolve().parent.parent
    m = json.loads((root / "build" / "objects.json").read_text(encoding="utf-8"))
    p, r = sources(m, Path(m["decomp"]), root / "build" / "ppc_data", set())
    print("\n".join(r))
    print(f"{len(p)} units")
